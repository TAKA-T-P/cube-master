/**
 * テンプレートにヒントを付ける（テンプレート自身がヒントを持っていればそれを使う）
 * @param {object[]} templates
 */
export const withHints = (templates) => templates.map((t) => (t.hint || !HINTS[t.id] ? t : { ...t, hint: HINTS[t.id] }));
